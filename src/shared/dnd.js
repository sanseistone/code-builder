// ============================================================
// 拖拽源共享状态（仅用于跨列表通信）
// 多个 DragList 共存（顶层区块列表 / 章节内子区块列表 / 列表项等），
// 用 listId 区分作用域，天然避免嵌套列表之间的拖拽串扰。
// 拖拽过程中的视觉状态（悬停位置等）由各 DragList 内部的响应式 ref 维护。
// ============================================================

export const dnd = {
  listId: null, // 拖拽源所在列表
  index: -1, // 拖拽源索引
}

export function resetDnd() {
  dnd.listId = null
  dnd.index = -1
}
